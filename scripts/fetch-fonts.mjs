/**
 * Fetch the web fonts the app uses and self-host them.
 *
 * The app does not call Google Fonts at runtime: the files are downloaded
 * once, kept in `public/fonts/`, and served from the app itself. A font
 * request that leaves the machine is a request that can fail, and a course
 * that is used on a phone on a train should not depend on it.
 *
 *   node scripts/fetch-fonts.mjs Archivo:400,500,600,700 Alfa+Slab+One:400
 *
 * Each argument is a family and its weights. The script writes the font
 * files to `public/fonts/`, the @font-face rules to
 * `app/assets/css/fonts.css`, and the licence of each family to
 * `public/fonts/`.
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const fontRoot = join(root, "public", "fonts")
const cssPath = join(root, "app", "assets", "css", "fonts.css")

const families = process.argv.slice(2)

if (families.length === 0) {
  console.error("usage: node scripts/fetch-fonts.mjs <Family:weights> ...")
  process.exit(1)
}

/**
 * A browser user agent.
 *
 * Google Fonts serves the modern formats to browsers that say they can take
 * them, so this is how the script gets woff2 instead of ttf.
 */
const AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"

/** The subsets worth keeping: Latin for most of it, Latin Extended for the rest. */
const KEEP_SUBSETS = new Set(["latin", "latin-ext"])

mkdirSync(fontRoot, { recursive: true })

const rules = []
const licences = []
const written = new Set()

for (const argument of families) {
  const [rawFamily, rawWeights] = argument.split(":")
  const family = rawFamily.replace(/\+/g, " ")
  const weights = (rawWeights ?? "400").split(",").join(";")

  const url =
    `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, "+")}` +
    `:wght@${weights}&display=swap`

  const response = await fetch(url, { headers: { "user-agent": AGENT } })
  if (!response.ok) {
    console.error(`could not fetch ${family}: ${response.status}`)
    process.exit(1)
  }

  const css = await response.text()

  // The response has one @font-face block per weight and subset.
  const blocks = css.split("@font-face").slice(1)

  for (const block of blocks) {
    const subset = (block.match(/\/\*\s*([a-z-]+)\s*\*\//) ?? [])[1] ?? "latin"
    if (!KEEP_SUBSETS.has(subset)) continue

    const source = (block.match(/url\((https:[^)]+\.woff2)\)/) ?? [])[1]
    const weight = (block.match(/font-weight:\s*([0-9]+)/) ?? [])[1] ?? "400"
    const style = (block.match(/font-style:\s*([a-z]+)/) ?? [])[1] ?? "normal"
    const range = (block.match(/unicode-range:\s*([^;]+);/) ?? [])[1]

    if (!source) continue

    const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}-${subset}.woff2`

    // The same file can be offered twice, for two unicode ranges. One copy
    // of the file, one rule for it.
    if (written.has(file)) continue
    written.add(file)

    const bytes = Buffer.from(await (await fetch(source, { headers: { "user-agent": AGENT } })).arrayBuffer())

    writeFileSync(join(fontRoot, file), bytes)

    rules.push(
      [
        "@font-face {",
        `  font-family: "${family}";`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        "  font-display: swap;",
        `  src: url("/fonts/${file}") format("woff2");`,
        range ? `  unicode-range: ${range};` : null,
        "}",
      ]
        .filter(Boolean)
        .join("\n"),
    )

    console.log(`  ${file} (${Math.round(bytes.length / 1024)} KB)`)
  }

  // The licence of the family, from the font's own repository.
  const slug = family.toLowerCase().replace(/\s+/g, "")
  try {
    const licence = await fetch(
      `https://raw.githubusercontent.com/google/fonts/main/ofl/${slug}/OFL.txt`,
      { headers: { "user-agent": AGENT } },
    )
    if (licence.ok) {
      const text = await licence.text()
      writeFileSync(join(fontRoot, `${slug}-OFL.txt`), text, "utf8")
      licences.push(slug)
    }
  } catch {
    console.warn(`  no licence fetched for ${family}`)
  }
}

writeFileSync(
  cssPath,
  `/* Self-hosted web fonts. Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n\n${rules.join("\n\n")}\n`,
  "utf8",
)

console.log(`\nwrote ${rules.length} font faces to ${cssPath.replace(root + "\\", "")}`)
console.log(`licences kept for: ${licences.length ? licences.join(", ") : "none"}`)
